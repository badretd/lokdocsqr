def test_check_policy_and_verify_uses_action_summary() -> None:
    class CapturingPolicy:
        def __init__(self) -> None:
            self.seen: list[ActionSummary] = []

        def decide(self, proposal: ActionSummary) -> PolicyDecision:
            self.seen.append(proposal)
            return PolicyDecision(PolicyAction.ALLOW, "ok", proposal)

    policy = CapturingPolicy()
    ctx = SimpleNamespace(policy=policy, scope=AllowScope(), verify_callback=None)
    node = SimpleNamespace(id="fs.write_file")
    payload = {"path_template": "x.txt", "content": "hi"}

    out = _check_policy_and_verify(node, ctx, payload, node_id="n1")

    assert out is payload
    assert policy.seen
    assert isinstance(policy.seen[0], ActionSummary)
    assert policy.seen[0].node_id == "n1"


