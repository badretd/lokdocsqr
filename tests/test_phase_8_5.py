def test_loop_batch_preview_calls_callback_when_opt_in(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    sentinel = object()
    monkeypatch.setattr(
        loop_batch_mod,
        "_resolve_child_graph",
        lambda ctx, payload: (None, sentinel),
    )

