def test_check_policy_and_verify_calls_validate_proposal_once_for_allow(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    import lokdocsqr.core.executor.engine as engine_mod

    calls: list[ActionSummary] = []
    real = engine_mod.validate_proposal

